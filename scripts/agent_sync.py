#!/usr/bin/env python3
"""Compile native agent entrypoints from the canonical repository contract."""
import argparse
import hashlib
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
contract = root / 'agent/contract.md'
digest = hashlib.sha256(contract.read_bytes()).hexdigest()
# Each host loads only its own entrypoint file, so both carry the full contract text; relative
# links are rebased from agent/ to the repository root.
text = ('<!-- Generated by scripts/agent_sync.py from agent/contract.md, the canonical authority; '
        'edit the contract first. -->\n'
        f'<!-- Contract SHA-256: `{digest}` -->\n\n'
        + contract.read_text().replace('](../', ']('))
wrong = []
for name in ('AGENTS.md', 'CLAUDE.md'):
    path = root / name
    if args.check:
        if not path.exists() or path.read_text() != text:
            wrong.append(name)
    else:
        path.write_text(text)
if wrong:
    raise SystemExit('Stale entrypoints: ' + ', '.join(wrong))
print('Entrypoints match canonical contract.' if args.check else 'Entrypoints generated.')
